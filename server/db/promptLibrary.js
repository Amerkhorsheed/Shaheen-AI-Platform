/**
 * Decide whether a stored prompt may be replaced by the current edition.
 *
 * The single rule the seeder applies to charters, modules, directives and
 * templates alike: a value is ours to replace only while it is still, exactly,
 * a value we shipped. The moment an administrator changes one character it
 * stops matching, and the platform never touches it again.
 *
 * @param {string} current  What the database holds now.
 * @param {string} target   The edition we would install.
 * @param {string[]} shipped Every value this platform has shipped for it.
 * @returns {boolean}
 */
function isUpgradableShippedValue(current, target, shipped) {
  const stored = (current || '').trim();
  if (!stored) return false;
  if (stored === (target || '').trim()) return false; // already current
  return (shipped || []).some((value) => (value || '').trim() === stored);
}

